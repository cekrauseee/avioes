const translations: Record<Locale, Record<TranslationKey, string>> = { pt, en }

export type TKey = TranslationKey

export function t(locale: Locale, key: TranslationKey): string {
  return translations[locale][key]
}

export function tf(locale: Locale, key: TranslationKey, vars: Record<string, string | number>): string {
  let s = translations[locale][key]
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function detectLocaleFromHeader(acceptLanguage: string | null): Locale {
  if (!acceptLanguage) return 'en'
  return /\bpt\b/i.test(acceptLanguage) ? 'pt' : 'en'
}

